HRESULT D3D12Backend::create(Mem m, uint64_t size, bool uav, Buffer& b) {
    b = {};
    D3D12_HEAP_PROPERTIES hp{};
    D3D12_RESOURCE_STATES state = D3D12_RESOURCE_STATE_COMMON;
    switch (m) {
    case Mem::Gpu: hp.Type = D3D12_HEAP_TYPE_DEFAULT; break;
    case Mem::Upload: hp.Type = D3D12_HEAP_TYPE_UPLOAD; state = D3D12_RESOURCE_STATE_GENERIC_READ; break;
    case Mem::Readback: hp.Type = D3D12_HEAP_TYPE_READBACK; state = D3D12_RESOURCE_STATE_COPY_DEST; break;
    case Mem::CpuWrite:
        hp = device->GetCustomHeapProperties(0, D3D12_HEAP_TYPE_UPLOAD);  // write-combined unless cache-coherent UMA
        if (writeCombine) hp.CPUPageProperty = D3D12_CPU_PAGE_PROPERTY_WRITE_COMBINE;
        break;
    case Mem::CpuRead: hp = device->GetCustomHeapProperties(0, D3D12_HEAP_TYPE_READBACK); break;
    }
    D3D12_RESOURCE_DESC d{};
    d.Dimension = D3D12_RESOURCE_DIMENSION_BUFFER;
    d.Width = size;
    d.Height = 1;
    d.DepthOrArraySize = 1;
    d.MipLevels = 1;
    d.Format = DXGI_FORMAT_UNKNOWN;
    d.SampleDesc.Count = 1;
    d.Layout = D3D12_TEXTURE_LAYOUT_ROW_MAJOR;
    d.Flags = uav ? D3D12_RESOURCE_FLAG_ALLOW_UNORDERED_ACCESS : D3D12_RESOURCE_FLAG_NONE;
    // Every byte is written before it is read: skip the driver's clear of new VRAM.
    const bool nz = m == Mem::Gpu && notZeroed_.load();
    HRESULT hr = device->CreateCommittedResource(&hp, nz ? D3D12_HEAP_FLAG_CREATE_NOT_ZEROED : D3D12_HEAP_FLAG_NONE, &d, state,
                                                 nullptr, IID_PPV_ARGS(&b.res));
    if (hr == E_INVALIDARG && nz) {  // runtime older than Windows 10 2004
        notZeroed_ = false;
        hr = device->CreateCommittedResource(&hp, D3D12_HEAP_FLAG_NONE, &d, state, nullptr, IID_PPV_ARGS(&b.res));
    }
    if (SUCCEEDED(hr)) {
        b.size = size;
        b.va = b.res->GetGPUVirtualAddress();
    }
    return hr;
}

bool D3D12Backend::supports(const PsdHeader& h) const {
    if (lost()) return false;
    if (h.compression == 1) return h.depth == 8 || h.depth == 16;
    return h.compression == 0 && h.depth == 8;
}

uint64_t D3D12Backend::device_bytes(const PsdHeader& h, int dw, int dh) const {
    const uint64_t rows = uint64_t(h.sourceChannels()) * h.height;
    const uint64_t out = align_up(uint64_t(dw) * dh * kPixelBytes, 256) + 256;
    if (h.compression != 1) return rows * h.width + 4 + out;  // raw planes are read in place
    const uint64_t in = align_up((rows + 1) * 4, 256) + align_up(h.imageDataBytes, 16) + 16;
    return in + rows * align_up(h.width, 16) + 16 + out;
}

std::unique_ptr<GpuStreamer> D3D12Backend::make_streamer(std::wstring& error) {
    if (lost()) {
        error = L"D3D12 device lost";
        return nullptr;
    }
    auto s = std::make_unique<D3D12Streamer>(shared_from_this());
    if (!s->init(error)) return nullptr;
    return s;
}

bool D3D12Backend::memory(uint64_t& freeBytes, uint64_t& totalBytes) {
    freeBytes = totalBytes = 0;
    DXGI_QUERY_VIDEO_MEMORY_INFO mi{};
    if (FAILED(adapter->QueryVideoMemoryInfo(0, DXGI_MEMORY_SEGMENT_GROUP_LOCAL, &mi))) return false;
    totalBytes = mi.Budget;
    freeBytes = mi.Budget > mi.CurrentUsage ? mi.Budget - mi.CurrentUsage : 0;
    return true;
}

std::wstring D3D12Backend::profile() {
    if (!profiling) return {};
    const uint64_t n = profImages.exchange(0), u = profUnpack.exchange(0), r = profResize.exchange(0);
    if (!n) return {};
    const double ms = 1000.0 / ticksPerSecond / double(n);
    return std::format(L"GPU per image: unpack {:.2f} ms, resize {:.2f} ms ({} images)", double(u) * ms, double(r) * ms, n);
}

std::wstring D3D12Backend::description() const {
    return std::format(L"D3D12 on {} ({}{})", name, uma ? L"UMA: zero-copy upload" : L"discrete: banded upload",
                       directResult ? L", result written to host memory" : L", result copied back");
}

// ---- D3D12Streamer ----------------------------------------------------------------------------

D3D12Streamer::~D3D12Streamer() {
    std::wstring ignored;
    if (copyFence_) wait(copyFence_.Get(), copyValue_, ignored);
    if (computeFence_) wait(computeFence_.Get(), computeValue_, ignored);
    for (Buffer& b : band_)
        if (b.res) b.res->Unmap(0, nullptr);
    if (event_) CloseHandle(event_);
}

bool D3D12Streamer::fail(HRESULT hr, const wchar_t* what, std::wstring& error) {
    g_->check_lost(hr);
    if (g_->lost()) hr = g_->device->GetDeviceRemovedReason();
    error = std::format(L"D3D12 {}: {}", what, hr_msg(hr));
    return false;
}

bool D3D12Streamer::init(std::wstring& error) {
    ID3D12Device* dev = g_->device.Get();
    HRESULT hr = dev->CreateCommandAllocator(D3D12_COMMAND_LIST_TYPE_COMPUTE, IID_PPV_ARGS(&computeAlloc_));
    if (SUCCEEDED(hr))
        hr = dev->CreateCommandList(0, D3D12_COMMAND_LIST_TYPE_COMPUTE, computeAlloc_.Get(), nullptr, IID_PPV_ARGS(&computeList_));
    if (SUCCEEDED(hr)) hr = computeList_->Close();
    if (SUCCEEDED(hr)) hr = dev->CreateFence(0, D3D12_FENCE_FLAG_NONE, IID_PPV_ARGS(&computeFence_));
    if (SUCCEEDED(hr)) hr = dev->CreateFence(0, D3D12_FENCE_FLAG_NONE, IID_PPV_ARGS(&copyFence_));
    if (SUCCEEDED(hr) && !g_->uma) {
        for (int i = 0; i < 2 && SUCCEEDED(hr); ++i) {
            hr = dev->CreateCommandAllocator(D3D12_COMMAND_LIST_TYPE_COPY, IID_PPV_ARGS(&copyAlloc_[i]));
            if (SUCCEEDED(hr)) hr = g_->create(Mem::Upload, kGpuBandBytes, false, band_[i]);
            const D3D12_RANGE none{0, 0};
            if (SUCCEEDED(hr)) hr = band_[i].res->Map(0, &none, reinterpret_cast<void**>(&bandPtr_[i]));
        }
        if (SUCCEEDED(hr))
            hr = dev->CreateCommandList(0, D3D12_COMMAND_LIST_TYPE_COPY, copyAlloc_[0].Get(), nullptr, IID_PPV_ARGS(&copyList_));
        if (SUCCEEDED(hr)) hr = copyList_->Close();
    }
    if (SUCCEEDED(hr)) hr = g_->create(Mem::Gpu, 256, true, status_);
    if (SUCCEEDED(hr) && g_->ticksPerSecond > 0) {
        D3D12_QUERY_HEAP_DESC qd{};
        qd.Type = D3D12_QUERY_HEAP_TYPE_TIMESTAMP;
        qd.Count = 3;
        hr = dev->CreateQueryHeap(&qd, IID_PPV_ARGS(&stamps_));
        if (SUCCEEDED(hr)) hr = g_->create(Mem::Readback, 3 * sizeof(uint64_t), false, stampsReadback_);
    }
    if (FAILED(hr)) return fail(hr, L"streamer setup", error);
    event_ = CreateEventW(nullptr, FALSE, FALSE, nullptr);
    if (!event_) {
        error = L"CreateEvent: " + win32_message(GetLastError());
        return false;
    }
    return true;
}

uint64_t D3D12Streamer::submit(Queue& q, ID3D12Fence* fence, uint64_t& counter, ID3D12CommandList* list) {
    std::lock_guard lk(q.m);
    q.q->ExecuteCommandLists(1, &list);
    q.q->Signal(fence, ++counter);
    return counter;
}

// Sleeps (no spinning: the encoders need the cores) until the fence reaches `value`.
bool D3D12Streamer::wait(ID3D12Fence* fence, uint64_t value, std::wstring& error) {
    if (fence->GetCompletedValue() >= value) return true;
    HRESULT hr = fence->SetEventOnCompletion(value, event_);
    if (FAILED(hr)) return fail(hr, L"fence", error);
    if (WaitForSingleObject(event_, kWaitTimeoutMs) == WAIT_OBJECT_0) return true;
    hr = g_->device->GetDeviceRemovedReason();
    return fail(FAILED(hr) ? hr : DXGI_ERROR_WAIT_TIMEOUT, L"waiting for the GPU", error);
}

bool D3D12Streamer::put(uint64_t dstOff, uint64_t bytes, const Filler& fill, FileStatus& file, std::wstring& error) {
    if (bytes == 0) return true;
    if (g_->uma) {
        uint8_t* p = nullptr;
        const D3D12_RANGE none{0, 0};
        HRESULT hr = in_.res->Map(0, &none, reinterpret_cast<void**>(&p));
        if (FAILED(hr)) return fail(hr, L"map", error);
        const bool ok = fill(p + dstOff, 0, size_t(bytes));
        const D3D12_RANGE written{size_t(dstOff), size_t(dstOff + bytes)};
        in_.res->Unmap(0, &written);
        if (!ok) file = {PP_FILE_TRUNCATED, L"file truncated inside the composite"};
        return ok;
    }
    for (uint64_t done = 0; done < bytes;) {
        const size_t n = size_t(std::min<uint64_t>(kGpuBandBytes, bytes - done));
        if (!fill(bandPtr_[cur_], done, n)) {
            file = {PP_FILE_TRUNCATED, L"file truncated inside the composite"};
            return false;
        }
        HRESULT hr = copyAlloc_[cur_]->Reset();
        if (SUCCEEDED(hr)) hr = copyList_->Reset(copyAlloc_[cur_].Get(), nullptr);
        if (FAILED(hr)) return fail(hr, L"copy list", error);
        copyList_->CopyBufferRegion(in_.res.Get(), dstOff + done, band_[cur_].res.Get(), 0, n);
        hr = copyList_->Close();
        if (FAILED(hr)) return fail(hr, L"copy list", error);
        bandDone_[cur_] = submit(g_->copy, copyFence_.Get(), copyValue_, copyList_.Get());
        cur_ ^= 1;
        // Before filling the other band, its previous copy (one band ago) must be done.
        if (!wait(copyFence_.Get(), bandDone_[cur_], error)) return false;
        done += n;
    }
    return true;
}

bool D3D12Streamer::begin(const PsdHeader& h, std::wstring& error) {
    abort();
    if (g_->lost()) {
        error = L"D3D12 device lost";
        return false;
    }
    w_ = h.width;
    h_ = h.height;
    channels_ = h.sourceChannels();
    depth_ = h.depth;
    compression_ = h.compression;
    return true;
}

bool D3D12Streamer::upload(const FileReader& f, const PsdHeader& h, FileStatus& file, std::wstring& error) {
    file = {};
    if (!begin(h, error)) return false;
    const uint64_t rows = uint64_t(channels_) * h_;
    if (compression_ == 0) {  // raw 8-bit: the colour planes are contiguous in the file; resized in place
        const uint64_t bytes = rows * w_;
        if (h.imageDataPos + bytes > h.fileSize) {
            file = {PP_FILE_TRUNCATED, L"file ends inside the composite"};
            return false;
        }
        if (!ensure(*g_, g_->uma ? Mem::CpuWrite : Mem::Gpu, bytes + 4, false, in_, error)) return false;
        staged_ = put(0, bytes, [&](uint8_t* dst, uint64_t off, size_t n) { return f.read_exact(h.imageDataPos + off, dst, n); },
                      file, error);
        return staged_;
    }
    RleLayout lay;
    file = read_rle_layout(f, h, lay);
    if (!file.ok()) return false;
    return upload_rle(h, lay.counts, lay.dataBytes,
                      [&](uint64_t off, uint8_t* dst, size_t n) { return f.read_exact(lay.dataPos + off, dst, n); }, file, error);
}

bool D3D12Streamer::upload_rle(const PsdHeader& h, const std::vector<uint32_t>& counts, uint64_t dataBytes,
                               const DataReader& read, FileStatus& file, std::wstring& error) {
    file = {};
    if (!begin(h, error)) return false;
    compression_ = 1;
    const uint64_t rows = uint64_t(channels_) * h_;
    compOffset_ = align_up((rows + 1) * 4, 256);
    const uint64_t inBytes = compOffset_ + align_up(dataBytes, 16) + 16;  // + slack: the kernel loads 16-byte blocks
    if (!ensure(*g_, g_->uma ? Mem::CpuWrite : Mem::Gpu, inBytes, false, in_, error)) return false;
    // + 16: the resize loads whole words past a row's last pixel
    if (!ensure(*g_, Mem::Gpu, rows * align_up(w_, 16) + 16, true, planes_, error)) return false;

    // Row offsets: prefix sums of the RLE table, produced in whatever pieces put() asks for.
    uint64_t acc = 0, next = 0;
    auto offsets = [&](uint8_t* dst, uint64_t off, size_t n) {
        uint32_t* o = reinterpret_cast<uint32_t*>(dst);
        for (uint64_t j = 0, i = off / 4; j < n / 4; ++j, ++i) {
            for (; next < i; ++next) acc += counts[next];
            o[j] = uint32_t(acc);
        }
        return true;
    };
    staged_ = put(0, (rows + 1) * 4, offsets, file, error) &&
              put(compOffset_, dataBytes, [&](uint8_t* dst, uint64_t off, size_t n) { return read(off, dst, n); }, file, error);
    return staged_;
}

bool D3D12Streamer::finish(int dw, int dh, uint8_t* dst, FileStatus& file, std::wstring& error) {
    file = {};
    if (!staged_) {
        error = L"D3D12: nothing uploaded";
        return false;
    }
    staged_ = false;
    if (!g_->uma && !wait(copyFence_.Get(), copyValue_, error)) return false;  // the last band is in VRAM
    const uint64_t outBytes = uint64_t(dw) * dh * kPixelBytes, statusOffset = align_up(outBytes, 256);
    const uint64_t total = statusOffset + 4;
    if (!ensure(*g_, g_->directResult ? Mem::CpuRead : Mem::Gpu, total, true, out_, error)) return false;
    if (!g_->directResult && !ensure(*g_, Mem::Readback, total, false, readback_, error)) return false;

    HRESULT hr = computeAlloc_->Reset();
    if (SUCCEEDED(hr)) hr = computeList_->Reset(computeAlloc_.Get(), nullptr);
    if (FAILED(hr)) return fail(hr, L"command list", error);
    ID3D12GraphicsCommandList* cl = computeList_.Get();
    cl->SetComputeRootSignature(g_->rs.Get());
    auto bind = [&](D3D12_GPU_VIRTUAL_ADDRESS t0, D3D12_GPU_VIRTUAL_ADDRESS t1, D3D12_GPU_VIRTUAL_ADDRESS u0) {
        cl->SetComputeRootShaderResourceView(kT0, t0);
        cl->SetComputeRootShaderResourceView(kT1, t1);
        cl->SetComputeRootUnorderedAccessView(kU0, u0);
        cl->SetComputeRootUnorderedAccessView(kU1, status_.va);
    };
    auto uav_barrier = [&](ID3D12Resource* r) {
        D3D12_RESOURCE_BARRIER b{};
        b.Type = D3D12_RESOURCE_BARRIER_TYPE_UAV;
        b.UAV.pResource = r;
        cl->ResourceBarrier(1, &b);
    };
    auto transition = [&](ID3D12Resource* r, D3D12_RESOURCE_STATES from, D3D12_RESOURCE_STATES to) {
        D3D12_RESOURCE_BARRIER b{};
        b.Type = D3D12_RESOURCE_BARRIER_TYPE_TRANSITION;
        b.Transition.pResource = r;
        b.Transition.Subresource = D3D12_RESOURCE_BARRIER_ALL_SUBRESOURCES;
        b.Transition.StateBefore = from;
        b.Transition.StateAfter = to;
        cl->ResourceBarrier(1, &b);
    };

    // Buffers are back in the common state at the start of every command list (they decay).
    const D3D12_RESOURCE_STATES common = D3D12_RESOURCE_STATE_COMMON, uav = D3D12_RESOURCE_STATE_UNORDERED_ACCESS;
    transition(status_.res.Get(), common, uav);
    transition(out_.res.Get(), common, uav);
    if (compression_ == 1) transition(planes_.res.Get(), common, uav);

    if (stamps_) cl->EndQuery(stamps_.Get(), D3D12_QUERY_TYPE_TIMESTAMP, 0);
    cl->SetPipelineState(g_->clear.Get());
    bind(in_.va, in_.va, status_.va);
    cl->Dispatch(1, 1, 1);
    uav_barrier(status_.res.Get());

    D3D12_GPU_VIRTUAL_ADDRESS planes = in_.va;  // raw: the planes as read from the file
    uint32_t pitch = w_;
    if (compression_ == 1) {
        const uint32_t rows = uint32_t(channels_) * h_;
        pitch = uint32_t(align_up(w_, 16));
        const uint32_t c[6] = {rows, w_ * uint32_t(depth_ / 8), depth_ == 16 ? 1u : 0u, w_, pitch, kGroupsPerX};
        cl->SetComputeRoot32BitConstants(kConstants, 6, c, 0);
        cl->SetPipelineState(g_->unpack.Get());
        bind(in_.va + compOffset_, in_.va, planes_.va);
        const uint32_t groups = (rows + kUnpackGroup - 1) / kUnpackGroup;
        cl->Dispatch(std::min(groups, kGroupsPerX), (groups + kGroupsPerX - 1) / kGroupsPerX, 1);
        transition(planes_.res.Get(), uav, D3D12_RESOURCE_STATE_NON_PIXEL_SHADER_RESOURCE);
        uav_barrier(status_.res.Get());
        planes = planes_.va;
    }
    if (stamps_) cl->EndQuery(stamps_.Get(), D3D12_QUERY_TYPE_TIMESTAMP, 1);
    const CubicFilter f = resize_filter(int(w_), dw);
    uint32_t c[10] = {w_, h_, pitch, pitch * h_, uint32_t(dw), uint32_t(dh), uint32_t(dw) * kPixelBytes, 0, 0, uint32_t(statusOffset)};
    std::memcpy(&c[7], &f.B, 4);
    std::memcpy(&c[8], &f.C, 4);
    cl->SetComputeRoot32BitConstants(kConstants, 10, c, 0);
    cl->SetPipelineState(g_->resize_pso(channels_, false, int(w_), dw));
    bind(planes, in_.va, out_.va);
    cl->Dispatch(UINT(dw + 31) / 32, UINT(dh + 7) / 8, 1);
    if (stamps_) {
        cl->EndQuery(stamps_.Get(), D3D12_QUERY_TYPE_TIMESTAMP, 2);
        cl->ResolveQueryData(stamps_.Get(), D3D12_QUERY_TYPE_TIMESTAMP, 0, 3, stampsReadback_.res.Get(), 0);
    }
    if (!g_->directResult) {
        transition(out_.res.Get(), uav, D3D12_RESOURCE_STATE_COPY_SOURCE);
        cl->CopyBufferRegion(readback_.res.Get(), 0, out_.res.Get(), 0, total);
    }
    hr = cl->Close();
    if (FAILED(hr)) return fail(hr, L"command list", error);
    const uint64_t done = submit(g_->compute, computeFence_.Get(), computeValue_, cl);
    if (!wait(computeFence_.Get(), done, error)) return false;

    ID3D12Resource* result = g_->directResult ? out_.res.Get() : readback_.res.Get();
    uint8_t* p = nullptr;
    const D3D12_RANGE readRange{0, size_t(total)};
    hr = result->Map(0, &readRange, reinterpret_cast<void**>(&p));
    if (FAILED(hr)) return fail(hr, L"map", error);
    std::memcpy(dst, p, size_t(outBytes));
    uint32_t bad;
    std::memcpy(&bad, p + statusOffset, 4);
    const D3D12_RANGE none{0, 0};
    result->Unmap(0, &none);
    uint64_t* t = nullptr;
    const D3D12_RANGE stampRange{0, 3 * sizeof(uint64_t)};
    if (stamps_ && SUCCEEDED(stampsReadback_.res->Map(0, &stampRange, reinterpret_cast<void**>(&t)))) {
        if (t[2] > t[0]) g_->measured(t[2] - t[0], uint64_t(w_) * h_, false);
        if (g_->profiling) {
            g_->profUnpack += t[1] - t[0];
            g_->profResize += t[2] - t[1];
            ++g_->profImages;
        }
        stampsReadback_.res->Unmap(0, &none);
    }
    if (bad != UINT32_MAX) {
        file = {PP_FILE_CORRUPT, std::format(L"corrupt RLE data in composite channel {} row {}", bad / h_, bad % h_)};
        return false;
    }
    return true;
}

RowSink* D3D12Streamer::decode_target(const PsdHeader& h, std::wstring& error) {
    if (!begin(h, error)) return nullptr;
    const uint64_t pitch = uint64_t(w_) * kPixelBytes, bytes = pitch * h_;
    if (!ensure(*g_, Mem::CpuWrite, bytes + 16, false, in_, error)) return nullptr;
    const D3D12_RANGE none{0, 0};
    uint8_t* p = nullptr;
    const HRESULT hr = in_.res->Map(0, &none, reinterpret_cast<void**>(&p));
    if (FAILED(hr)) {
        fail(hr, L"map", error);
        return nullptr;
    }
    decoded_.base = p;
    decoded_.pitch = pitch;
    return &decoded_;
}

std::unique_ptr<GpuImage> D3D12Streamer::resize_decoded(int dw, int dh, std::wstring& error) {
    if (!decoded_.base) {
        error = L"D3D12: nothing decoded";
        return nullptr;
    }
    const uint64_t pitch = decoded_.pitch;
    const D3D12_RANGE written{0, size_t(pitch * h_)};
    in_.res->Unmap(0, &written);
    decoded_.base = nullptr;

    const uint64_t outBytes = uint64_t(dw) * dh * kPixelBytes, statusOffset = align_up(outBytes, 256);
    Buffer img;
    if (!g_->take_image(statusOffset + 4, img, error)) return nullptr;
    struct Giveback {  // the buffer goes back to the pool unless it ends up in the image
        D3D12Backend& g;
        Buffer& b;
        ~Giveback() {
            if (b.res) g.give_image(std::move(b));
        }
    } giveback{*g_, img};

    HRESULT hr = computeAlloc_->Reset();
    if (SUCCEEDED(hr)) hr = computeList_->Reset(computeAlloc_.Get(), nullptr);
    if (FAILED(hr)) {
        fail(hr, L"command list", error);
        return nullptr;
    }
    // Without directResult the kernel writes VRAM (out_) and the GPU copies that into the pooled
    // readback buffer, which stays in the copy-destination state.
    if (!g_->directResult && !ensure(*g_, Mem::Gpu, statusOffset + 4, true, out_, error)) return nullptr;
    ID3D12Resource* target = g_->directResult ? img.res.Get() : out_.res.Get();
    const D3D12_GPU_VIRTUAL_ADDRESS targetVa = g_->directResult ? img.va : out_.va;
    ID3D12GraphicsCommandList* cl = computeList_.Get();
    D3D12_RESOURCE_BARRIER b[2] = {};
    for (int i = 0; i < 2; ++i) {
        b[i].Type = D3D12_RESOURCE_BARRIER_TYPE_TRANSITION;
        b[i].Transition.Subresource = D3D12_RESOURCE_BARRIER_ALL_SUBRESOURCES;
        b[i].Transition.StateBefore = D3D12_RESOURCE_STATE_COMMON;
        b[i].Transition.StateAfter = D3D12_RESOURCE_STATE_UNORDERED_ACCESS;
    }
    b[0].Transition.pResource = target;
    b[1].Transition.pResource = status_.res.Get();
    cl->ResourceBarrier(2, b);
    cl->SetComputeRootSignature(g_->rs.Get());
    if (stamps_) {
        cl->EndQuery(stamps_.Get(), D3D12_QUERY_TYPE_TIMESTAMP, 0);
        cl->EndQuery(stamps_.Get(), D3D12_QUERY_TYPE_TIMESTAMP, 1);  // no unpack
    }
    const CubicFilter f = resize_filter(int(w_), dw);
    uint32_t c[10] = {w_, h_, uint32_t(pitch), 0, uint32_t(dw), uint32_t(dh), uint32_t(dw) * kPixelBytes, 0, 0, uint32_t(statusOffset)};
    std::memcpy(&c[7], &f.B, 4);
    std::memcpy(&c[8], &f.C, 4);
    cl->SetComputeRoot32BitConstants(kConstants, 10, c, 0);
    cl->SetPipelineState(g_->resize_pso(4, true, int(w_), dw));
    cl->SetComputeRootShaderResourceView(kT0, in_.va);
    cl->SetComputeRootShaderResourceView(kT1, in_.va);
    cl->SetComputeRootUnorderedAccessView(kU0, targetVa);
    cl->SetComputeRootUnorderedAccessView(kU1, status_.va);
    cl->Dispatch(UINT(dw + 31) / 32, UINT(dh + 7) / 8, 1);
    if (stamps_) {
        cl->EndQuery(stamps_.Get(), D3D12_QUERY_TYPE_TIMESTAMP, 2);
        cl->ResolveQueryData(stamps_.Get(), D3D12_QUERY_TYPE_TIMESTAMP, 0, 3, stampsReadback_.res.Get(), 0);
    }
    if (!g_->directResult) {
        b[0].Transition.StateBefore = D3D12_RESOURCE_STATE_UNORDERED_ACCESS;
        b[0].Transition.StateAfter = D3D12_RESOURCE_STATE_COPY_SOURCE;
        cl->ResourceBarrier(1, b);
        cl->CopyBufferRegion(img.res.Get(), 0, out_.res.Get(), 0, outBytes);
    }
    hr = cl->Close();
    if (FAILED(hr)) {
        fail(hr, L"command list", error);
        return nullptr;
    }
    const uint64_t done = submit(g_->compute, computeFence_.Get(), computeValue_, cl);
    if (!wait(computeFence_.Get(), done, error)) return nullptr;

    uint8_t* data = nullptr;
    const D3D12_RANGE readRange{0, size_t(outBytes)};
    hr = img.res->Map(0, &readRange, reinterpret_cast<void**>(&data));
    if (FAILED(hr)) {
        fail(hr, L"map", error);
        return nullptr;
    }
    uint64_t* t = nullptr;
    const D3D12_RANGE stampRange{0, 3 * sizeof(uint64_t)}, none{0, 0};
    if (stamps_ && SUCCEEDED(stampsReadback_.res->Map(0, &stampRange, reinterpret_cast<void**>(&t)))) {
        if (t[2] > t[0]) g_->measured(t[2] - t[0], uint64_t(w_) * h_, true);
        if (g_->profiling) {
            g_->profResize += t[2] - t[1];
            ++g_->profImages;
        }
        stampsReadback_.res->Unmap(0, &none);
    }
    return std::make_unique<D3D12Image>(g_, std::move(img), data);
}

void D3D12Streamer::abort() {
    if (decoded_.base) {
        const D3D12_RANGE none{0, 0};
        in_.res->Unmap(0, &none);
        decoded_.base = nullptr;
    }
    std::wstring ignored;
    if (copyValue_) wait(copyFence_.Get(), copyValue_, ignored);  // in-flight copies still read the bands
    if (computeValue_) wait(computeFence_.Get(), computeValue_, ignored);
    staged_ = false;
}

