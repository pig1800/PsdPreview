// D3D12 compute backend: any Windows GPU (AMD, Intel, Qualcomm Adreno, NVIDIA) and WARP, the
// software rasterizer that ships with Windows. Kernels: gpu_d3d12.hlsl, compiled to DXIL at
// build time.
//
// Per streamer: a command list for each of two copy allocators (one per band) and one for
// compute, two fences (copy, compute) and an event to sleep on. All streamers share one compute
// queue and one copy queue. Buffers are grow-only per streamer (kept across the batch's images)
// and bound as root descriptors, so there are no descriptor heaps.
//
// Memory, by adapter kind:
//   discrete  the compressed rows are read into two upload-heap bands and copied into VRAM on
//             the copy queue, band k + 1 being read while band k copies (like the CUDA path)
//   UMA       (integrated GPUs: Adreno, AMD/Intel APUs, WARP) the CPU reads the file straight
//             into memory the GPU reads (a custom heap with the upload heap's CPU properties):
//             no bands, no copies
//   both      when the driver allows a UAV in CPU-readable memory (a custom heap with the
//             readback heap's properties), the resize kernel writes its result straight there;
//             otherwise into VRAM, then copied into a readback buffer.
//
// Hybrid path (UMA only): the CPU decodes the composite into a mapped CPU-writable buffer, the
// GPU resizes it into a pooled CPU-readable buffer (or VRAM + a copy into one, as above) that
// the encoder reads in place.
//
// Non-cache-coherent UMA (CacheCoherentUMA false): the CPU-writable heaps are write-combined
// (uncached), so the CPU only ever writes them, sequentially (file reads, the decoder's merged
// rows, the RLE offsets); everything the CPU reads (results) is in readback-type, write-back
// memory, mapped after the GPU's fence so Map can invalidate the CPU caches. A driver may not
// allow a UAV there, or get it wrong: the self-tests check results byte for byte, including
// a result buffer reused after the CPU has read and written it, and fall back to copying
// results (directResult false), then to the full GPU path (no hybrid).
// PP_D3D12_NONCOHERENT=1 makes the CPU-writable heaps write-combined on any UMA adapter and
// PP_D3D12_DIRECT=0 turns off directResult, to test those paths.
