// Root parameters, see PP_RS in gpu_d3d12.hlsl.
enum Root : UINT { kConstants = 0, kT0 = 1, kT1 = 2, kU0 = 3, kU1 = 4 };
constexpr UINT kUnpackGroup = 64;   // GROUP in the shader: rows (threads) per group
constexpr UINT kGroupsPerX = 32768;  // unpack dispatch: groups per X dimension (max 65535)
constexpr DWORD kWaitTimeoutMs = 60000;

std::wstring hr_msg(HRESULT hr) { return std::format(L"0x{:08X} {}", uint32_t(hr), win32_message(DWORD(hr))); }

uint64_t align_up(uint64_t v, uint64_t a) { return (v + a - 1) / a * a; }

// Environment variable `name` is set and starts with `first`.
bool env_is(const char* name, char first) {
    char v[4] = {};
    size_t len = 0;
    return getenv_s(&len, v, sizeof v, name) == 0 && len > 0 && v[0] == first;
}

enum class Mem {
    Gpu,       // default heap (VRAM; system memory on UMA)
    Upload,    // upload heap: CPU-written bands
    Readback,  // readback heap: copy destination the CPU reads
    CpuWrite,  // custom heap like the upload heap, but usable as a shader resource (UMA input)
    CpuRead,   // custom heap like the readback heap, but a UAV (the result, written in place)
};

struct Buffer {
    ComPtr<ID3D12Resource> res;
    uint64_t size = 0;
    D3D12_GPU_VIRTUAL_ADDRESS va = 0;
};

struct Queue {
    ComPtr<ID3D12CommandQueue> q;
    std::mutex m;  // a submission and its fence signal stay together
};

class D3D12Backend final : public GpuBackend, public std::enable_shared_from_this<D3D12Backend> {
public:
    bool supports(const PsdHeader& h) const override;
    uint64_t device_bytes(const PsdHeader& h, int dw, int dh) const override;
    std::unique_ptr<GpuStreamer> make_streamer(std::wstring& error) override;
    bool memory(uint64_t& freeBytes, uint64_t& totalBytes) override;
    std::wstring description() const override;
    std::wstring profile() override;

    HRESULT create(Mem m, uint64_t size, bool uav, Buffer& b);
    bool lost() const { return lost_.load(); }
    void check_lost(HRESULT hr) {
        if (hr == DXGI_ERROR_DEVICE_REMOVED || hr == DXGI_ERROR_DEVICE_RESET || hr == DXGI_ERROR_DEVICE_HUNG) lost_ = true;
    }

    ComPtr<IDXGIAdapter3> adapter;
    ComPtr<ID3D12Device> device;
    Queue compute, copy;
    ComPtr<ID3D12RootSignature> rs;
    ComPtr<ID3D12PipelineState> clear, unpack, resize1, resize3, resize4;
    ComPtr<ID3D12PipelineState> resizeRgba;  // hybrid path: 4-byte pixels decoded by the CPU
    // Variants with a fixed horizontal tap count (FIXED in the shader), RGB and RGBA.
    static constexpr int kFixedTaps[4] = {8, 12, 16, 24};
    ComPtr<ID3D12PipelineState> resize3Fixed[4], resizeRgbaFixed[4];
    // The resize for this scale: the fixed variant whose tap count covers it, else the general one.
    ID3D12PipelineState* resize_pso(int channels, bool rgba, int w, int dw) const {
        const float fx = std::max(float(w) / float(dw), 1.0f);
        const int taps = int(4.0f * fx) + 2;  // as the shader's table check
        for (int i = 0; i < 4; ++i)
            if (taps <= kFixedTaps[i]) {
                if (rgba && resizeRgbaFixed[i]) return resizeRgbaFixed[i].Get();
                if (!rgba && channels == 3 && resize3Fixed[i]) return resize3Fixed[i].Get();
                break;
            }
        if (rgba) return resizeRgba.Get();
        return channels == 1 ? resize1.Get() : channels == 3 ? resize3.Get() : resize4.Get();
    }
    std::wstring name;
    bool warp = false, uma = false, coherentUma = false;
    bool writeCombine = false;  // PP_D3D12_NONCOHERENT: CPU-writable heaps write-combined
    bool directResult = false;  // Mem::CpuRead works: the result needs no copy
    bool hybridOk = false;      // UMA, and the hybrid path passed its self-test
    uint64_t maxBuffer = 0;     // largest buffer the kernels address (32-bit offsets) and the GPU maps
    double seconds_per_mpx(bool hybrid) const override { return gpuSecondsPerMpx[hybrid].load(); }
    bool integrated() const override { return uma; }
    bool hybrid() const override { return hybridOk; }
    void trim() override {
        std::lock_guard lk(imagesMutex_);
        freeImages_.clear();
    }

    // Results of the hybrid path: CPU-readable UAV buffers (Mem::CpuRead), reused through a pool.
    bool take_image(uint64_t need, Buffer& b, std::wstring& error) {
        {
            std::lock_guard lk(imagesMutex_);
            size_t best = freeImages_.size();
            for (size_t i = 0; i < freeImages_.size(); ++i)
                if (freeImages_[i].size >= need && (best == freeImages_.size() || freeImages_[i].size < freeImages_[best].size)) best = i;
            if (best < freeImages_.size()) {
                b = std::move(freeImages_[best]);
                freeImages_.erase(freeImages_.begin() + ptrdiff_t(best));
                return true;
            }
        }
        b = {};
        return ensure_image(need, b, error);
    }
    void give_image(Buffer&& b) {
        std::lock_guard lk(imagesMutex_);
        freeImages_.push_back(std::move(b));
    }
    bool ensure_image(uint64_t need, Buffer& b, std::wstring& error);
    void measured(uint64_t ticks, uint64_t pixels, bool hybrid) {  // one image's kernel time
        if (pixels < (1u << 18)) return;  // tiny images (the self-test) are all fixed overhead
        const double v = double(ticks) / ticksPerSecond / (double(pixels) / 1e6);
        std::atomic<double>& e = gpuSecondsPerMpx[hybrid];
        double old = e.load();
        while (!e.compare_exchange_weak(old, old > 0 ? 0.8 * old + 0.2 * v : v)) {}
    }

    bool profiling = false;     // PP_GPU_PROFILE: report the kernels' times
    double ticksPerSecond = 0;  // timestamps (0: the queue has none)
    std::atomic<double> gpuSecondsPerMpx[2] = {0, 0};  // full GPU path, hybrid path
    std::atomic<uint64_t> profImages{0}, profUnpack{0}, profResize{0};  // timestamp ticks

private:
    std::mutex imagesMutex_;
    std::vector<Buffer> freeImages_;
    std::atomic<bool> lost_{false};
    std::atomic<bool> notZeroed_{true};  // D3D12_HEAP_FLAG_CREATE_NOT_ZEROED accepted
};

// Grows `b` to at least `need` bytes (some headroom, so a batch's images rarely reallocate).
bool ensure(D3D12Backend& g, Mem m, uint64_t need, bool uav, Buffer& b, std::wstring& error) {
    if (b.res && b.size >= need) return true;
    b = {};
    if (need > g.maxBuffer) {
        error = std::format(L"GPU buffer of {} MB is over the limit", need >> 20);
        return false;
    }
    HRESULT hr = g.create(m, std::min(g.maxBuffer, align_up(need + need / 4, 1 << 16)), uav, b);
    if (FAILED(hr)) hr = g.create(m, need, uav, b);
    if (FAILED(hr)) {
        g.check_lost(hr);
        error = std::format(L"D3D12: allocating {} MB: {}", need >> 20, hr_msg(hr));
        return false;
    }
    return true;
}

bool D3D12Backend::ensure_image(uint64_t need, Buffer& b, std::wstring& error) {
    // the kernel's UAV, or the destination of a copy from it
    return directResult ? ensure(*this, Mem::CpuRead, need, true, b, error) : ensure(*this, Mem::Readback, need, false, b, error);
}

// A hybrid-path result: the pooled buffer stays mapped while the encoder reads it.
class D3D12Image final : public GpuImage {
public:
    D3D12Image(std::shared_ptr<D3D12Backend> g, Buffer&& b, uint8_t* p) : g_(std::move(g)), b_(std::move(b)) { data = p; }
    ~D3D12Image() override {
        const D3D12_RANGE none{0, 0};
        b_.res->Unmap(0, &none);
        g_->give_image(std::move(b_));
    }

private:
    std::shared_ptr<D3D12Backend> g_;
    Buffer b_;
};

// Rows of a mapped buffer, for the CPU decoder.
struct MappedRows final : RowSink {
    uint8_t* base = nullptr;
    uint64_t pitch = 0;
    uint8_t* row(uint32_t y) override { return base + y * pitch; }
};

class D3D12Streamer final : public GpuStreamer {
public:
    explicit D3D12Streamer(std::shared_ptr<D3D12Backend> g) : g_(std::move(g)) {}
    ~D3D12Streamer() override;
    bool init(std::wstring& error);
    bool upload(const FileReader& f, const PsdHeader& h, FileStatus& file, std::wstring& error) override;
    bool finish(int dw, int dh, uint8_t* dst, FileStatus& file, std::wstring& error) override;
    void abort() override;
    RowSink* decode_target(const PsdHeader& h, std::wstring& error) override;
    std::unique_ptr<GpuImage> resize_decoded(int dw, int dh, std::wstring& error) override;

    // Fills `n` bytes at dst with the composite's compressed rows from byte `off` on.
    using DataReader = std::function<bool(uint64_t off, uint8_t* dst, size_t n)>;
    bool upload_rle(const PsdHeader& h, const std::vector<uint32_t>& counts, uint64_t dataBytes, const DataReader& read,
                    FileStatus& file, std::wstring& error);

private:
    using Filler = std::function<bool(uint8_t* dst, uint64_t off, size_t n)>;
    bool begin(const PsdHeader& h, std::wstring& error);
    // Writes `bytes` produced by fill() into in_ at `dstOff`: straight into mapped memory (UMA)
    // or through the bands and the copy queue.
    bool put(uint64_t dstOff, uint64_t bytes, const Filler& fill, FileStatus& file, std::wstring& error);
    uint64_t submit(Queue& q, ID3D12Fence* fence, uint64_t& counter, ID3D12CommandList* list);
    bool wait(ID3D12Fence* fence, uint64_t value, std::wstring& error);
    bool fail(HRESULT hr, const wchar_t* what, std::wstring& error);

    std::shared_ptr<D3D12Backend> g_;
    ComPtr<ID3D12CommandAllocator> copyAlloc_[2], computeAlloc_;
    ComPtr<ID3D12GraphicsCommandList> copyList_, computeList_;
    ComPtr<ID3D12Fence> copyFence_, computeFence_;
    uint64_t copyValue_ = 0, computeValue_ = 0, bandDone_[2] = {};
    HANDLE event_ = nullptr;
    Buffer band_[2];
    uint8_t* bandPtr_[2] = {};
    int cur_ = 0;
    Buffer in_, planes_, out_, readback_, status_;
    ComPtr<ID3D12QueryHeap> stamps_;  // profiling: before / after the unpack, after the resize
    Buffer stampsReadback_;

    // the current image
    uint32_t w_ = 0, h_ = 0;
    int channels_ = 0, depth_ = 8, compression_ = 0;
    uint64_t compOffset_ = 0;  // RLE: compressed rows in in_, after the rows + 1 offsets
    bool staged_ = false;
    MappedRows decoded_;  // hybrid path: in_ mapped for the CPU decoder (base null: not mapped)
};

